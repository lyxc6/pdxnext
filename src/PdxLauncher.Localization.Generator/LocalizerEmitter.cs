namespace PdxLauncher.Localization.Generator;

using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

/// <summary>把资源名列表写成 <c>Localizer</c> 的 partial 与 <c>Keys</c> 常量类。</summary>
internal static class LocalizerEmitter
{
    /// <summary>生成并把源码交给编译器。</summary>
    internal static void AddTo(SourceProductionContext context, IEnumerable<string> names)
    {
        context.AddSource("Localizer.Strings.g.cs", SourceText.From(Emit(names), Encoding.UTF8));
    }

    internal static string Emit(IEnumerable<string> names)
    {
        var list = names.ToList();
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated>");
        builder.AppendLine("//   由 src/PdxLauncher.Localization.Generator 在编译时生成，不要手改。");
        builder.AppendLine("//   改文案请改 src/PdxLauncher.App/Strings/<lang>/Resources.resw。");
        builder.AppendLine("// </auto-generated>");
        builder.AppendLine();
        builder.AppendLine("namespace PdxLauncher.App.Localization;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>界面文案入口的生成部分。</summary>");
        builder.AppendLine("public sealed partial class Localizer");
        builder.AppendLine("{");
        builder.AppendLine("    private static readonly (string Key, string Identifier)[] AllKeys =");
        builder.AppendLine("    [");
        foreach (var name in list)
        {
            builder.Append("        (\"").Append(name).Append("\", \"").Append(name).AppendLine("\"),");
        }

        builder.AppendLine("    ];");
        builder.AppendLine();
        foreach (var name in list)
        {
            builder.Append("    public string ").Append(name).Append(" => Format(Keys.").Append(name).AppendLine(");");
        }

        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine("/// <summary>文案资源名常量（与 Resources.resw 的 data name 一一对应）。</summary>");
        builder.AppendLine("internal static class Keys");
        builder.AppendLine("{");
        foreach (var name in list)
        {
            builder.Append("    public const string ").Append(name).Append(" = \"").Append(name).AppendLine("\";");
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    internal static IEnumerable<string> Placeholders(string value)
    {
        return System.Text.RegularExpressions.Regex
            .Matches(value, @"\{(\d+)\}", System.Text.RegularExpressions.RegexOptions.CultureInvariant)
            .Cast<System.Text.RegularExpressions.Match>()
            .Select(match => match.Value)
            .OrderBy(token => token, StringComparer.Ordinal);
    }
}
