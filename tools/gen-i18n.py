#!/usr/bin/env python3
"""生成界面文案表（Strings.g.cs）。

用法（仓库根或任意目录都能跑）：

    python tools/gen-i18n.py            # 校验文案源并重写 src/PdxLauncher.App/Localization/Strings.g.cs
    python tools/gen-i18n.py --check    # 只校验：键集一致、值合法、生成结果已是最新（CI/提交前用）

文案源：tools/i18n/<lang>/<area>.json，扁平点分键 -> 字符串。
  - 每个 <lang> 目录下的所有 .json 会被合并（同一个键出现在两个文件里视为错误）。
  - 两种语言的键集必须完全一致，缺键/多键都报错。
  - 值里的 {0} {1} 占位符必须在两种语言里一一对应。
  - 键的每一段必须是 [a-z][a-z0-9]*；生成的标识符 = 各段首字母大写后拼接
    （app.name -> AppName），不同键生成了同一个标识符时报错。

生成物是机器写的，不要手改；改文案请改 tools/i18n/*/*.json 后重新运行本脚本。
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parent.parent
SOURCE_ROOT = ROOT / "tools" / "i18n"
TARGET = ROOT / "src" / "PdxLauncher.App" / "Localization" / "Strings.g.cs"

# 语言键 -> (目录名, 生成的表名)：与 Core 的 UiLanguages 一一对应。
LANGUAGES = (
    ("zh-CN", "TableZhCN"),
    ("en-US", "TableEnUS"),
)
FALLBACK_LANGUAGE = "en-US"

KEY_SEGMENT = re.compile(r"^[a-z][a-zA-Z0-9]*$")
PLACEHOLDER = re.compile(r"\{(\d+)\}")

HEADER = """// <auto-generated>
//   This file is generated by tools/gen-i18n.py. Do not edit it by hand.
//   改文案请改 tools/i18n/zh-CN/*.json 与 tools/i18n/en-US/*.json，然后运行：
//       python tools/gen-i18n.py
// </auto-generated>

namespace PdxLauncher.App.Localization;
"""


class SourceError(Exception):
    """文案源不合法：消息直接打印给改文案的人看。"""


def load_language(language: str) -> dict[str, str]:
    directory = SOURCE_ROOT / language
    if not directory.is_dir():
        raise SourceError("缺少文案目录：" + str(directory.relative_to(ROOT)))

    merged: dict[str, str] = {}
    origin: dict[str, Path] = {}
    for path in sorted(directory.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as error:
            raise SourceError(str(path.relative_to(ROOT)) + " 不是合法 JSON：" + str(error)) from error
        if not isinstance(data, dict):
            raise SourceError(str(path.relative_to(ROOT)) + " 的顶层必须是对象")

        for key, value in data.items():
            if key in merged:
                raise SourceError(
                    "键 " + key + " 同时出现在 " + str(origin[key].relative_to(ROOT)) + " 与 " + str(path.relative_to(ROOT))
                )
            if not isinstance(key, str) or not isinstance(value, str):
                raise SourceError(str(path.relative_to(ROOT)) + " 里 " + str(key) + " 的值必须是字符串")
            merged[key] = value
            origin[key] = path

    if not merged:
        raise SourceError("文案目录 " + language + " 是空的")

    return merged


def validate_style(language: str, table: dict[str, str]) -> None:
    for key, value in table.items():
        segments = key.split(".")
        if len(segments) < 2:
            raise SourceError("[" + language + "] 键 " + key + " 至少要两段（区域.名称）")
        for segment in segments:
            if not KEY_SEGMENT.match(segment):
                raise SourceError("[" + language + "] 键 " + key + " 的段 " + segment + " 必须匹配 [a-z][a-zA-Z0-9]*")
        if not value.strip():
            raise SourceError("[" + language + "] 键 " + key + " 的值是空白")
        if value != value.strip():
            raise SourceError("[" + language + "] 键 " + key + " 的值首尾不能有空白")


def identifier_for(key: str) -> str:
    return "".join(segment[:1].upper() + segment[1:] for segment in key.split("."))


def build_identifiers(keys: list[str]) -> dict[str, str]:
    identifiers: dict[str, str] = {}
    owners: dict[str, str] = {}
    for key in keys:
        identifier = identifier_for(key)
        if identifier in owners:
            raise SourceError("键 " + keys[owners[identifier]] + " 与 " + key + " 生成了同一个标识符 " + identifier)
        owners[identifier] = key
        identifiers[key] = identifier
    return identifiers


def csharp_literal(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n") + '"'


def render(tables: dict[str, dict[str, str]], keys: list[str], identifiers: dict[str, str]) -> str:
    lines: list[str] = [HEADER]
    lines.append("using System.Collections.Generic;")
    lines.append("")
    lines.append("/// <summary>界面文案表（由 tools/gen-i18n.py 生成，手改会被覆盖）。</summary>")
    lines.append("public sealed partial class Localizer")
    lines.append("{")

    for language, table_name in LANGUAGES:
        lines.append("    private static readonly Dictionary<string, string> " + table_name + " = new(StringComparer.Ordinal)")
        lines.append("    {")
        for key in keys:
            lines.append("        [" + csharp_literal(key) + "] = " + csharp_literal(tables[language][key]) + ",")
        lines.append("    };")
        lines.append("")

    lines.append("    private static readonly (string Key, string Identifier)[] AllKeys =")
    lines.append("    [")
    for key in keys:
        lines.append("        (" + csharp_literal(key) + ", " + csharp_literal(identifiers[key]) + "),")
    lines.append("    ];")
    lines.append("")

    for key in keys:
        lines.append("    public string " + identifiers[key] + " => Format(" + csharp_literal(key) + ");")
    lines.append("}")
    lines.append("")
    lines.append("/// <summary>文案键常量：code-behind / ViewModel 里传键用这里，避免手写字面量。</summary>")
    lines.append("internal static class Keys")
    lines.append("{")
    for key in keys:
        lines.append("    public const string " + identifiers[key] + " = " + csharp_literal(key) + ";")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    check_only = "--check" in argv[1:]

    try:
        tables: dict[str, dict[str, str]] = {}
        for language, _ in LANGUAGES:
            table = load_language(language)
            validate_style(language, table)
            tables[language] = table

        primary = LANGUAGES[0][0]
        primary_keys = set(tables[primary].keys())
        for language, _ in LANGUAGES[1:]:
            other_keys = set(tables[language].keys())
            missing = sorted(primary_keys - other_keys)
            extra = sorted(other_keys - primary_keys)
            if missing or extra:
                details: list[str] = []
                if missing:
                    details.append("缺少 " + str(len(missing)) + " 个键：" + ", ".join(missing[:20]))
                if extra:
                    details.append("多出 " + str(len(extra)) + " 个键：" + ", ".join(extra[:20]))
                raise SourceError("[" + language + "] 与 [" + primary + "] 键集不一致（" + "；".join(details) + "）")

            for key, value in tables[primary].items():
                expected = PLACEHOLDER.findall(value)
                actual = PLACEHOLDER.findall(tables[language][key])
                if expected != actual:
                    raise SourceError(
                        "键 " + key + " 的占位符不一致：[" + primary + "] " + str(expected) + " vs [" + language + "] " + str(actual)
                    )

        keys = sorted(tables[primary].keys())
        identifiers = build_identifiers(keys)
        content = render(tables, keys, identifiers)
    except SourceError as error:
        print("[gen-i18n] 失败：" + str(error), file=sys.stderr)
        return 1

    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
    if current.replace("\r\n", "\n") == content:
        print("[gen-i18n] 文案源合法，" + str(len(keys)) + " 个键，生成物已是最新")
        return 0

    if check_only:
        print("[gen-i18n] 生成物已过期：运行 python tools/gen-i18n.py 重新生成", file=sys.stderr)
        return 1

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8", newline="\n")
    print("[gen-i18n] 已写入 " + str(TARGET.relative_to(ROOT)) + "（" + str(len(keys)) + " 个键）")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
